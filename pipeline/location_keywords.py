def all_keywords() -> list[str]:
    """전체 키워드를 평탄화한 단일 목록으로 반환(중복 제거, 입력 순서 유지)."""
    seen: set[str] = set()
    flat: list[str] = []
    for words in LOCATION_KEYWORDS.values():
        for word in words:
            if word not in seen:
                seen.add(word)
                flat.append(word)
    return flat


def format_keyword_guide() -> str:
    """프롬프트 주입용 markdown 블록을 생성한다.

    카테고리별로 키워드를 한 줄에 나열한다. 사용 지침(전부 쓰지 말 것,
    관련 있는 것만, Guard 우선)은 호출하는 프롬프트 쪽에서 함께 명시한다.
    """
    lines: list[str] = []
    for category, words in LOCATION_KEYWORDS.items():
        lines.append(f"- **{category}**: {' · '.join(words)}")
    return "\n".join(lines)
